import { pack, unpack } from './codec.ts';

/**
 * plan.md §25.4 A2 — the study pack: everything one participant's session
 * needs, carried in the URL *fragment* (`/study#p=…`).
 *
 * **Why the instrument is not in the app.** `STUDY.md` is explicit that the
 * mechanism questions and the control-arm text must never be shown before the
 * test and never shipped publicly — the study measures whether someone can
 * answer them cold. A `/study` route that bundled them would put both in a JS
 * file anyone can read. So the app ships only the *runner*; the instrument
 * arrives inside the link, generated by `pnpm study links` from `STUDY.md`. A
 * URL fragment is never sent to a server, so it also keeps "no network" literal.
 *
 * Both arms get the same consent, the same timings and the same five
 * questions; only `material` differs — a reading (`text`) or a set of lessons
 * to work through (`app`).
 *
 * A pack is a stranger's input, exactly like the shareable URL (§15.2): every
 * field is validated, every string is length-bounded, and every task link must
 * be a same-origin path so a crafted link cannot send a participant elsewhere.
 */

export const PACK_VERSION = 1;

export type StudyArm = 'app' | 'text';

export interface StudyTask {
  label: string;
  /** A same-origin path (`/learn/eviction`), never a URL with a host. */
  href: string;
}

export interface StudyQuestion {
  id: string;
  title: string;
  text: string;
}

export interface StudyPack {
  v: typeof PACK_VERSION;
  /** Which study this is (`spring-pilot`); echoed into the result so codes cannot be mixed up. */
  study: string;
  /** The participant's code (`P07`) — deliberately not a name. */
  pid: string;
  arm: StudyArm;
  /** Consent paragraphs, shown before anything starts. */
  consent: string[];
  material: {
    seconds: number;
    title: string;
    intro: string;
    /** The control-arm reading; empty for the `app` arm. Blank-line-separated blocks, `### ` headings. */
    body: string;
    /** The `app` arm's lessons; empty for the `text` arm. */
    tasks: StudyTask[];
  };
  test: {
    seconds: number;
    questions: StudyQuestion[];
  };
}

export const LIMITS = {
  id: 40,
  title: 200,
  paragraph: 2000,
  consentParagraphs: 8,
  body: 24_000,
  tasks: 6,
  questions: 8,
  question: 2400,
  seconds: { materialMin: 5, materialMax: 3600, testMin: 10, testMax: 3600 },
} as const;

const ID = /^[A-Za-z0-9][A-Za-z0-9_-]*$/;
/** `/learn/eviction` or `/tools/btree?fanout=4` — one leading slash, no host, no `//`. */
const SAME_ORIGIN_PATH = /^\/(?!\/)[A-Za-z0-9_\-/]*(\?[A-Za-z0-9_\-=&%.]*)?$/;

export type PackResult = { ok: true; pack: StudyPack } | { ok: false; error: string };

function isRecord(x: unknown): x is Record<string, unknown> {
  return typeof x === 'object' && x !== null && !Array.isArray(x);
}

function str(x: unknown, max: number, what: string): string {
  if (typeof x !== 'string') throw new Error(`${what} must be text`);
  if (x.length > max) throw new Error(`${what} is too long`);
  return x;
}

function seconds(x: unknown, min: number, max: number, what: string): number {
  if (typeof x !== 'number' || !Number.isInteger(x) || x < min || x > max) {
    throw new Error(`${what} must be a whole number between ${String(min)} and ${String(max)}`);
  }
  return x;
}

function list(x: unknown, max: number, what: string): unknown[] {
  if (!Array.isArray(x)) throw new Error(`${what} must be a list`);
  if (x.length > max) throw new Error(`${what} has too many entries`);
  return x as unknown[];
}

function record(x: unknown, what: string): Record<string, unknown> {
  if (!isRecord(x)) throw new Error(`${what} is missing`);
  return x;
}

/** Validates an untrusted value into a `StudyPack`, or says which field was wrong. */
export function validatePack(raw: unknown): PackResult {
  try {
    const p = record(raw, 'The pack');
    if (p.v !== PACK_VERSION) throw new Error('This link is from a different version of the study kit');

    const study = str(p.study, LIMITS.id, 'The study id');
    const pid = str(p.pid, LIMITS.id, 'The participant code');
    if (!ID.test(study) || !ID.test(pid)) throw new Error('The study id and participant code may only use letters, digits, - and _');
    if (p.arm !== 'app' && p.arm !== 'text') throw new Error('The arm must be "app" or "text"');

    const consent = list(p.consent, LIMITS.consentParagraphs, 'The consent text').map((c) =>
      str(c, LIMITS.paragraph, 'A consent paragraph'),
    );
    if (consent.length === 0) throw new Error('A study needs consent text');

    const m = record(p.material, 'The material');
    const tasks = list(m.tasks, LIMITS.tasks, 'The task list').map((t) => {
      const task = record(t, 'A task');
      const href = str(task.href, 200, 'A task link');
      if (!SAME_ORIGIN_PATH.test(href)) throw new Error('A task link must be a path on this site');
      return { label: str(task.label, LIMITS.title, 'A task label'), href };
    });
    const body = str(m.body, LIMITS.body, 'The reading');
    if (p.arm === 'text' && body.trim() === '') throw new Error('The text arm needs a reading');
    if (p.arm === 'app' && tasks.length === 0) throw new Error('The app arm needs at least one task');

    const t = record(p.test, 'The test');
    const seen = new Set<string>();
    const questions = list(t.questions, LIMITS.questions, 'The questions').map((q) => {
      const question = record(q, 'A question');
      const id = str(question.id, LIMITS.id, 'A question id');
      if (!ID.test(id) || seen.has(id)) throw new Error('Question ids must be unique and use letters, digits, - and _');
      seen.add(id);
      return {
        id,
        title: str(question.title, LIMITS.title, 'A question title'),
        text: str(question.text, LIMITS.question, 'A question'),
      };
    });
    if (questions.length === 0) throw new Error('A study needs at least one question');

    return {
      ok: true,
      pack: {
        v: PACK_VERSION,
        study,
        pid,
        arm: p.arm,
        consent,
        material: {
          seconds: seconds(m.seconds, LIMITS.seconds.materialMin, LIMITS.seconds.materialMax, 'The material time'),
          title: str(m.title, LIMITS.title, 'The material title'),
          intro: str(m.intro, LIMITS.paragraph, 'The material introduction'),
          body,
          tasks,
        },
        test: {
          seconds: seconds(t.seconds, LIMITS.seconds.testMin, LIMITS.seconds.testMax, 'The test time'),
          questions,
        },
      },
    };
  } catch (e) {
    return { ok: false, error: e instanceof Error ? e.message : 'The study link could not be read' };
  }
}

export async function encodePack(p: StudyPack): Promise<string> {
  return pack(p);
}

export async function decodePack(code: string): Promise<PackResult> {
  const raw = await unpack(code);
  if (raw === null) return { ok: false, error: 'This study link is damaged or incomplete — ask for a new one' };
  return validatePack(raw);
}

/** The pack code inside a location hash (`#p=…`), or `null` when there is none. */
export function packCodeFromHash(hash: string): string | null {
  const m = /^#p=([A-Za-z0-9_-]+)$/.exec(hash);
  return m?.[1] ?? null;
}
